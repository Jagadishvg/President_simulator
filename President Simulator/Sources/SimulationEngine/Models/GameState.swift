import Foundation

/// A cabinet member / adviser with attributes that affect policy execution and events.
public struct CabinetMember: Codable, Equatable, Hashable {
    public let role: String            // e.g. "Secretary of State"
    public let name: String
    public var competence: Double      // 0-100, improves policy outcomes
    public var loyalty: Double         // 0-100, less likely to resign/leak
    public var integrity: Double       // 0-100, resists scandal/corruption
    public var ambition: Double        // 0-100, may pursue own agenda
    public var policyAlignment: Double // 0-100, alignment with president's agenda
    public var isResigned: Bool = false
    public var scandalFlag: String? = nil

    public init(role: String, name: String, competence: Double = 60, loyalty: Double = 60,
                integrity: Double = 60, ambition: Double = 50, policyAlignment: Double = 60) {
        self.role = role
        self.name = name
        self.competence = min(max(competence, 0), 100)
        self.loyalty = min(max(loyalty, 0), 100)
        self.integrity = min(max(integrity, 0), 100)
        self.ambition = min(max(ambition, 0), 100)
        self.policyAlignment = min(max(policyAlignment, 0), 100)
    }
}

/// A recorded presidential decision for history and delayed-consequence prerequisites.
public struct DecisionRecord: Codable, Equatable {
    public let turn: Int
    public let eventId: String
    public let choiceId: String
    public let choiceTitle: String
    public let narrative: String
    public let statChanges: [String: Double]
    public let historyFlags: [String]
    public let date: Date

    public init(turn: Int, eventId: String, choiceId: String, choiceTitle: String,
                narrative: String, statChanges: [String: Double], historyFlags: [String]) {
        self.turn = turn
        self.eventId = eventId
        self.choiceId = choiceId
        self.choiceTitle = choiceTitle
        self.narrative = narrative
        self.statChanges = statChanges
        self.historyFlags = historyFlags
        self.date = Date()
    }
}

/// A fictional news item generated by the simulation.
public struct NewsItem: Codable, Equatable, Identifiable {
    public let id: UUID
    public let turn: Int
    public let headline: String
    public let summary: String
    public let category: String       // e.g. "economy", "foreign", "politics", "crisis"
    public let tone: String            // "positive", "negative", "neutral", "mixed"
    public let relatedEventId: String?

    public init(turn: Int, headline: String, summary: String, category: String,
                tone: String, relatedEventId: String? = nil) {
        self.id = UUID()
        self.turn = turn
        self.headline = headline
        self.summary = summary
        self.category = category
        self.tone = tone
        self.relatedEventId = relatedEventId
    }
}

/// The complete state of a presidency. This is the single source of truth
/// persisted to disk and mutated only by the SimulationEngine.
public struct GameState: Codable, Equatable {
    public static let saveVersion: Int = 1

    public var saveVersion: Int = GameState.saveVersion
    public var presidentName: String = "President"
    public var presidentParty: String = "Independent"
    public var leadershipStyle: String = "Pragmatic"
    public var difficulty: String = "Normal"

    public var turn: Int = 0                 // 0-based decision count
    public var year: Int = 1                 // 1...4
    public var termMaxTurns: Int = 16        // one decision per quarter ~ 4 years
    public var isInaugurated: Bool = false
    public var isGameOver: Bool = false
    public var gameOverReason: String? = nil

    public var stats: NationalStats = NationalStats()
    public var voterGroups: [String: Double] = [:]   // groupId -> support 0-100
    public var congressHouseSupport: Double = 55
    public var congressSenateSupport: Double = 55
    public var cabinet: [String: CabinetMember] = [:] // role -> member
    public var internationalRelations: [String: Double] = [:] // countryId -> relation -100...100

    public var history: [DecisionRecord] = []
    public var historyFlags: Set<String> = []         // permanent flags set by decisions
    public var pendingDelayedEffects: [DelayedEffect] = []
    public var news: [NewsItem] = []
    public var recentEventIds: [String] = []           // last N events, to avoid repetition

    public var achievements: Set<String> = []
    public var unlockedScenarios: Set<String> = ["default"]

    public var totalDecisions: Int { history.count }

    public mutating func advanceTurn() {
        turn += 1
        year = 1 + (turn / 4)   // 4 turns per year
        if year > 4 { year = 4 }
        if turn >= termMaxTurns {
            isGameOver = true
            gameOverReason = "termEnded"
        }
        // Shift recent events window
        if recentEventIds.count > 8 { recentEventIds.removeFirst() }
    }

    public var overallApproval: Double {
        guard !voterGroups.isEmpty else { return stats.publicApproval.value }
        return voterGroups.values.reduce(0, +) / Double(voterGroups.count)
    }
}

/// A delayed consequence scheduled to fire after a number of turns or when a condition holds.
public struct DelayedEffect: Codable, Equatable {
    public let id: UUID
    public let triggerTurn: Int            // fires when state.turn >= this
    public let effect: Effect
    public let sourceEventId: String
    public let description: String
    public var hasFired: Bool = false

    public init(id: UUID = UUID(), triggerTurn: Int, effect: Effect, sourceEventId: String, description: String) {
        self.id = id
        self.triggerTurn = triggerTurn
        self.effect = effect
        self.sourceEventId = sourceEventId
        self.description = description
    }
}

/// An effect applied by a choice or delayed consequence.
public struct Effect: Codable, Equatable {
    public var statChanges: [String: Double] = [:]      // statKey -> delta
    public var budgetDelta: Double = 0                  // applied to treasuryBudget
    public var voterGroupChanges: [String: Double] = [:] // groupId -> delta
    public var congressDelta: Double = 0
    public var internationalReputationDelta: Double = 0
    public var historyFlags: [String] = []              // flags to set permanently
    public var historyFlagsToRemove: [String] = []
    public var hiddenRiskProbability: Double = 0        // 0-1, chance a scandal flag appears later
    public var hiddenRiskFlag: String? = nil
    public var newsHeadline: String? = nil
    public var newsSummary: String? = nil
    public var newsCategory: String = "politics"
    public var newsTone: String = "neutral"
    public var followUpEventId: String? = nil
    public var followUpDelay: Int = 0                   // turns before follow-up event becomes eligible
}
